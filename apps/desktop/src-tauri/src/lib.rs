fn is_allowed_app_navigation(url: &tauri::Url) -> bool {
    match url.scheme() {
        "tauri" | "about" => true,
        "http" | "https" => matches!(
            (url.host_str(), url.port()),
            (Some("tauri.localhost"), None)
                | (Some("localhost"), Some(1420))
                | (Some("127.0.0.1"), Some(1420))
        ),
        _ => false,
    }
}


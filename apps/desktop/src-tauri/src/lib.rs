pub fn typescript_exporter() -> Typescript {
    Typescript::default().header(
        "// This file is auto-generated by tauri-specta. Do not edit manually.\n// Run `cargo test -p fr-desktop export_bindings` to regenerate.",
    )
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let _ = tracing_subscriber::fmt()
        .with_env_filter(
            EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new("info")),
        )
        .try_init();

    let builder = specta_builder();
    let app_state = AppState::initialize();

    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .manage(app_state)
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let handle = app.handle().clone();
            tauri::async_runtime::spawn(async move {
                let state = handle.state::<AppState>();
                match MediaProxyServer::start(state.storage.clone()).await {
                    Ok(proxy) => {
                        tracing::info!(
                            "Local Range-streaming media proxy listening on {}",
                            proxy.addr()
                        );
                        state.set_media_proxy(Arc::new(proxy));
                    }
                    Err(err) => {
                        tracing::error!("Failed to start local media proxy: {err}");
                    }
                }
            });
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running FR Universal App");
}

